"""Measure chunk-level detection: model-scored chunks against the heuristic.

Issue #39 asks that chunk aggregation and thresholds be measured against a
baseline rather than swapped in. The baseline is the arithmetic rule the agent
lane used for every chunk in every scenario:

    10 + failure_rate*40 + min(unique_dst*3, 30) + min(events//5, 20)

A chunk counts as attack-bearing when any event inside it carries label=1, which
is the only ground truth the shipped scenarios have. Two numbers matter and they
pull against each other: recall over attack-bearing chunks, and how much of the
log gets flagged to buy it. A rule that flags everything has perfect recall and
is useless, which is exactly the failure mode measured here.

    python -m scripts.eval_chunk_scoring
"""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
SCENARIOS = ROOT / "data" / "demo" / "scenarios"
OUT = ROOT / "reports" / "chunk_scoring.md"


def _chunk_labels(chunks, events: pd.DataFrame) -> list[int]:
    """1 when any event in the chunk is labelled attack.

    Read off `chunk.events` rather than looked up in the parent frame by index.
    EventChunk slices carry a RESET index -- every chunk starts at 0 -- so
    `parent.loc[chunk.events.index]` silently returns the parent's first rows
    for every chunk. The first version of this function did that and reported 0
    attack-bearing chunks for aiims_ransomware, a log with 35 labelled attack
    events in it.
    """
    out = []
    for c in chunks:
        if "label" not in c.events.columns:
            out.append(0)
            continue
        lab = pd.to_numeric(c.events["label"], errors="coerce").fillna(0)
        out.append(int((lab > 0).any()))
    return out


def _prf(flags: list[bool], labels: list[int]) -> dict:
    tp = sum(1 for f, l in zip(flags, labels) if f and l)
    fp = sum(1 for f, l in zip(flags, labels) if f and not l)
    fn = sum(1 for f, l in zip(flags, labels) if not f and l)
    precision = tp / (tp + fp) if tp + fp else 0.0
    recall = tp / (tp + fn) if tp + fn else 0.0
    f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
    return {"tp": tp, "fp": fp, "fn": fn,
            "precision": round(precision, 3), "recall": round(recall, 3),
            "f1": round(f1, 3),
            "flagged_share": round(sum(flags) / len(flags), 3) if flags else 0.0}


def measure(scenario: str) -> dict | None:
    from src.agents.chunker import chunk_all_strategies
    from src.agents.detection import (BASE_THRESHOLD, SCORE_COLUMN,
                                      THRESHOLD_BY_PRIORITY, _heuristic_score)
    from src.agents.investigation import run as investigate
    from src.agents.orchestrator import _engineer_for_scoring
    from src.agents.summarizer import summarize_chunk

    path = SCENARIOS / f"{scenario}.csv"
    if not path.exists():
        return None
    raw = pd.read_csv(path)
    if "label" not in raw.columns or not (pd.to_numeric(raw["label"], errors="coerce").fillna(0) > 0).any():
        return None

    scored_events, state = _engineer_for_scoring(raw)
    chunks = chunk_all_strategies(scored_events).get("time_window", [])
    if not chunks:
        return None
    labels = _chunk_labels(chunks, scored_events)
    triaged = investigate(chunks, [summarize_chunk(c) for c in chunks]).output.get("triaged", [])

    model_flags, heur_flags = [], []
    for record, chunk in zip(triaged, chunks):
        priority = record.get("priority", "routine")
        threshold = THRESHOLD_BY_PRIORITY.get(priority, BASE_THRESHOLD)

        per_event = pd.to_numeric(chunk.events.get(SCORE_COLUMN), errors="coerce") \
            if SCORE_COLUMN in chunk.events.columns else None
        model = float(per_event.max()) if per_event is not None and per_event.notna().any() else 0.0
        model_flags.append(model >= threshold)

        heuristic, _ = _heuristic_score(record.get("stats", {}), priority)
        heur_flags.append(heuristic >= threshold)

    return {
        "scenario": scenario,
        "events": int(len(raw)),
        "chunks": len(chunks),
        "attack_chunks": sum(labels),
        "calibration": (state.get("calibration") or {}).get("basis", "unknown"),
        "model": _prf(model_flags, labels),
        "heuristic": _prf(heur_flags, labels),
    }


def main() -> None:
    rows = [r for r in (measure(p.stem) for p in sorted(SCENARIOS.glob("*.csv"))) if r]
    if not rows:
        print("no labelled scenarios found")
        return

    lines = [
        "# Chunk scoring: model against the heuristic baseline", "",
        "Generated by `python -m scripts.eval_chunk_scoring`. Issue #39.", "",
        "A chunk is attack-bearing when any event inside it carries `label=1`.",
        "`flagged` is the share of chunks above their threshold -- the cost side",
        "of recall, and the number that shows a rule flagging everything.", "",
        "| scenario | chunks | attack | method | precision | recall | F1 | flagged |",
        "|---|---:|---:|---|---:|---:|---:|---:|",
    ]
    for r in rows:
        for name in ("model", "heuristic"):
            m = r[name]
            lines.append(
                f"| {r['scenario']} | {r['chunks']} | {r['attack_chunks']} | {name} "
                f"| {m['precision']} | {m['recall']} | {m['f1']} | {m['flagged_share']} |")
    lines += ["", "## Calibration used", ""]
    for r in rows:
        lines.append(f"- `{r['scenario']}`: {r['calibration']}")
    lines += ["",
              "The model path scores the whole log once through",
              "`src.shared.live_analyze._score`, so a chunk is as anomalous as its",
              "most anomalous event and both lanes agree about that event. Scoring",
              "each chunk against its own range instead pins the top event of every",
              "chunk at 100 and flagged 36 of 36 chunks on aiims_ransomware.", ""]
    OUT.write_text("\n".join(lines))
    print("\n".join(lines))
    print(f"\nwrote {OUT.relative_to(ROOT)}")
    print(json.dumps(rows, indent=1)[:400])


if __name__ == "__main__":
    main()
